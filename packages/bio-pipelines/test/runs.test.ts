// Сквозные тесты прогонов: план → фоновый запуск → состояние и маскировка лога; отказы (повтор, чужой вид плана,
// изменённый файл); остановка по плану; список прогонов; исход по логу после перезапуска сервера; права на файлы.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { appendFileSync, existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { test } from 'node:test';
import { connect, planIdOf, runIdOf, waitFinished } from './harness.js';
test('Nextflow: план → запуск в фоне → состояние с прогрессом, отчётом и скрытым паролем; план одноразовый', async () => {
	const { call, calls, project, data, close } = await connect();
	const planned = await call('bio_plan', { program: 'nextflow', pipeline: project, paramsFile: join(project, 'params.json') });
	const planId = planIdOf(planned.text);
	assert.ok(planId, planned.text);
	const started = await call('bio_run', { planId });
	assert.equal(started.isError, false, started.text);
	assert.match(started.text, /^Started nextflow in the background \(PID \d+\)\./);
	const runId = runIdOf(started.text);
	assert.ok(runId);
	const status = await waitFinished(call, runId);
	assert.match(status, /^State: succeeded \(exit code 0\)/m);
	assert.match(status, /Progress:\n {2}FASTQC: 2 submitted\n {2}MULTIQC: 0 submitted, 1 cached/);
	assert.match(status, /http:\/\/user:\*\*\*@proxy\.local:3128/);
	assert.ok(!status.includes('hunter2'));
	const runArgs = calls().find(c => c.args[0] === 'run' && !c.args.includes('-preview'));
	assert.ok(runArgs?.args.includes('-with-report'));
	assert.equal(runArgs?.cwd, project);
	const runs = join(data, 'runs');
	assert.equal(statSync(runs).mode & 0o777, 0o700);
	assert.equal(statSync(join(runs, `${runId}.log`)).mode & 0o777, 0o600);
	assert.equal(statSync(join(runs, `${runId}.json`)).mode & 0o777, 0o600);
	assert.ok(existsSync(join(runs, `${runId}-report.html`)));
	const again = await call('bio_run', { planId });
	assert.equal(again.isError, true);
	assert.match(again.text, /was not found \(plans are used once/);
	const list = await call('bio_runs');
	assert.match(list.text, new RegExp(`^${runId} {2}nextflow {2}succeeded`, 'm'));
	await close();
});
test('запуск отклоняется, если файл пайплайна изменился; план остановки не запускает прогон', async () => {
	const { call, calls, project, close } = await connect();
	const planned = await call('bio_plan', { program: 'snakemake', pipeline: join(project, 'smk'), cores: 2 });
	appendFileSync(join(project, 'smk', 'workflow', 'Snakefile'), 'rule extra:\n    output: "b.txt"\n');
	const changed = await call('bio_run', { planId: planIdOf(planned.text) });
	assert.equal(changed.isError, true);
	assert.match(changed.text, /nothing was started: files changed since the plan: .*Snakefile/);
	assert.ok(!calls().some(c => c.program === 'snakemake' && !c.args.includes('--dry-run') && c.args.includes('--cores') && !c.args.includes('--version')));
	const foreign = await call('bio_run', { planId: '00000000-0000-4000-8000-000000000000' });
	assert.match(foreign.text, /was not found/);
	const bad = await call('bio_run', { planId: '../../etc/passwd' });
	assert.match(bad.text, /Unknown plan id/);
	await close();
});
test('Snakemake и miniwdl: прогон до конца, прогресс шагов, каталог результатов miniwdl создаётся', async () => {
	const { call, calls, project, close } = await connect();
	const smk = await call('bio_run', { planId: planIdOf((await call('bio_plan', { program: 'snakemake', pipeline: join(project, 'smk'), cores: 3 })).text) });
	const smkStatus = await waitFinished(call, runIdOf(smk.text)!);
	assert.match(smkStatus, /^State: succeeded/m);
	assert.match(smkStatus, /Progress:\n {2}5 of 5 steps \(100%\) done/);
	const smkRun = calls().find(c => c.program === 'snakemake' && c.args.includes('--cores') && !c.args.includes('--dry-run'));
	assert.equal(smkRun?.args[smkRun.args.indexOf('--cores') + 1], '3');
	const out = join(project, 'wdl-runs');
	const wdlPlan = await call('bio_plan', { program: 'miniwdl', pipeline: join(project, 'wdl', 'align.wdl'), inputs: join(project, 'wdl', 'inputs.json'), outputDir: out });
	const wdl = await call('bio_run', { planId: planIdOf(wdlPlan.text) });
	const wdlStatus = await waitFinished(call, runIdOf(wdl.text)!);
	assert.match(wdlStatus, /^State: succeeded/m);
	assert.match(wdlStatus, /"outputs"/);
	assert.ok(existsSync(out));
	const wdlRun = calls().find(c => c.program === 'miniwdl' && c.args[0] === 'run' && !c.args.includes('--json'));
	assert.deepEqual(wdlRun?.args.slice(-3), ['--dir', out, '--no-color']);
	await close();
});
test('остановка: план показывает идущий прогон, применение шлёт SIGTERM, повтор и чужой вид плана отклоняются', async () => {
	const { call, project, close } = await connect({ FAKE_HANG: '1' });
	const started = await call('bio_run', { planId: planIdOf((await call('bio_plan', { program: 'nextflow', pipeline: project })).text) });
	const runId = runIdOf(started.text)!;
	await new Promise(resolve => setTimeout(resolve, 300));
	assert.match((await call('bio_run_status', { runId })).text, /^State: running \(PID \d+\)/m);
	const stop = await call('bio_run_stop_plan', { runId });
	assert.equal(stop.isError, false, stop.text);
	assert.match(stop.text, /PID \d+, running for \d+s/);
	assert.match(stop.text, /Nextflow cancels its running tasks/);
	const stopId = planIdOf(stop.text)!;
	const wrongKind = await call('bio_run', { planId: stopId });
	assert.match(wrongKind.text, /was made by bio_run_stop_plan, not by bio_plan/);
	const applied = await call('bio_run_stop_apply', { planId: stopId });
	assert.equal(applied.isError, false, applied.text);
	assert.match(applied.text, /^SIGTERM sent to nextflow/);
	const status = await waitFinished(call, runId);
	assert.match(status, /^State: failed \(exit code 143\)/m);
	assert.match(status, /Killing running tasks/);
	const again = await call('bio_run_stop_apply', { planId: stopId });
	assert.match(again.text, /was not found/);
	const finished = await call('bio_run_stop_plan', { runId });
	assert.equal(finished.isError, true);
	assert.match(finished.text, /is not running/);
	await close();
});
test('после перезапуска сервера: код выхода неизвестен — исход по логу; старые записи удаляются', async () => {
	const first = await connect();
	const { call, close } = await connect({}, { data: first.data, project: first.project });
	await first.close();
	await call('bio_runs');
	const runs = join(first.data, 'runs');
	const dead = spawnSync(process.execPath, ['-e', '0']).pid!;
	const id = '11111111-1111-4111-8111-111111111111';
	writeFileSync(join(runs, `${id}.log`), 'executor >  local (3)\n[a1/b2c3d4] Submitted process > FASTQC (1)\nSucceeded   : 3\n', { mode: 0o600 });
	writeFileSync(join(runs, `${id}.json`), JSON.stringify({ id, program: 'nextflow', pipeline: join(first.project, 'main.nf'), launchDir: first.project, args: [], outputs: 'x', pid: dead, startedAt: new Date().toISOString(), log: join(runs, `${id}.log`) }), { mode: 0o600 });
	const status = await call('bio_run_status', { runId: id });
	assert.match(status.text, /^State: finished; exit code unknown \(the server restarted during the run\), the log suggests it succeeded/m);
	assert.match(status.text, /Progress:\n {2}executor > local \(3\)\n {2}FASTQC: 1 submitted/);
	const old = '22222222-2222-4222-8222-222222222222';
	const week = new Date(Date.now() - 8 * 24 * 3600 * 1000).toISOString();
	writeFileSync(join(runs, `${old}.log`), 'old\n');
	writeFileSync(join(runs, `${old}.json`), JSON.stringify({ id: old, program: 'snakemake', pipeline: '/x/Snakefile', launchDir: '/x', args: [], outputs: 'x', pid: dead, startedAt: week, finishedAt: week, exitCode: 0, log: join(runs, `${old}.log`) }));
	const list = await call('bio_runs');
	assert.ok(list.text.includes(id) && !list.text.includes(old));
	assert.deepEqual(readdirSync(runs).filter(name => name.startsWith(old)), []);
	await close();
});
