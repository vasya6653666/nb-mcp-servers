// Тесты пар «план → применение» для скачивания и удаления моделей Ollama (успех, прогресс, повтор, чужой id, план
// другого вида, другой сервер, изменившийся digest) и хранения планов (права 0700/0600, срок жизни).
import assert from 'node:assert/strict';
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readdirSync, statSync, utimesSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { IPullPlan, loadPlan, newPlanId, PLAN_TTL_MS, plansRoot, savePlan } from '../src/plans.js';
import { fakeOllama, IOllamaState, ollamaModel } from './fakes.js';
import { connect, planIdOf } from './harness.js';
test('скачивание: план ничего не качает, применение — по id один раз, с прогрессом', async () => {
	const state: IOllamaState = { models: [], loaded: [] };
	const ollama = await fakeOllama(state);
	const { call, progress, close } = await connect({ OLLAMA_HOST: ollama.url });
	const plan = await call('lm_pull_plan', { model: 'qwen2.5-coder:7b' });
	assert.equal(plan.isError, false);
	assert.match(plan.text, /Download size: unknown before the download starts/);
	assert.match(plan.text, /Not present locally/);
	assert.equal(ollama.calls.some(c => c.path === '/api/pull'), false);
	const id = planIdOf(plan.text)!;
	const applied = await call('lm_pull_apply', { planId: id });
	assert.equal(applied.isError, false, applied.text);
	assert.match(applied.text, /Pulled qwen2\.5-coder:7b into Ollama .* \(new model\)/);
	assert.match(applied.text, /digest b{64}/);
	assert.deepEqual(ollama.calls.find(c => c.path === '/api/pull')!.body, { model: 'qwen2.5-coder:7b', stream: true });
	assert.ok(progress.length >= 1, 'progress notifications');
	const again = await call('lm_pull_apply', { planId: id });
	assert.equal(again.isError, true);
	assert.match(again.text, /was not found \(plans are used once/);
	const foreign = await call('lm_pull_apply', { planId: newPlanId() });
	assert.equal(foreign.isError, true);
	assert.match(foreign.text, /was not found/);
	const bad = await call('lm_pull_apply', { planId: '../../etc/passwd' });
	assert.match(bad.text, /Unknown plan id/);
	await close();
	await ollama.close();
});
test('скачивание: план другого сервера и план другого вида отклоняются', async () => {
	const state: IOllamaState = { models: [ollamaModel('llama3.2:latest')], loaded: [] };
	const first = await fakeOllama(state);
	const second = await fakeOllama(state);
	const data = mkdtempSync(join(tmpdir(), 'nb-lm-shared-'));
	const a = await connect({ OLLAMA_HOST: first.url }, data);
	const pullId = planIdOf((await a.call('lm_pull_plan', { model: 'llama3.2' })).text)!;
	const deleteId = planIdOf((await a.call('lm_delete_plan', { model: 'llama3.2' })).text)!;
	const wrongKind = await a.call('lm_pull_apply', { planId: deleteId });
	assert.equal(wrongKind.isError, true);
	assert.match(wrongKind.text, /was made by lm_delete_plan, not by lm_pull_plan/);
	await a.close();
	const b = await connect({ OLLAMA_HOST: second.url }, data);
	const moved = await b.call('lm_pull_apply', { planId: pullId });
	assert.equal(moved.isError, true);
	assert.match(moved.text, /made for another Ollama server/);
	const movedDelete = await b.call('lm_delete_apply', { planId: deleteId });
	assert.match(movedDelete.text, /made for another Ollama server/);
	assert.equal(second.calls.some(c => c.path === '/api/pull' || c.path === '/api/delete'), false);
	await b.close();
	await first.close();
	await second.close();
});
test('удаление: план с размером и digest, отказ при другом digest, применение один раз', async () => {
	const state: IOllamaState = { models: [ollamaModel('llama3.2:latest')], loaded: ['llama3.2:latest'] };
	const ollama = await fakeOllama(state);
	const { call, close } = await connect({ OLLAMA_HOST: ollama.url });
	const plan = await call('lm_delete_plan', { model: 'llama3.2' });
	assert.match(plan.text, /Delete model llama3\.2:latest from Ollama/);
	assert.match(plan.text, /size 2\.0 GB, modified 2026-10-01T10:00:00Z, digest a{64}/);
	assert.match(plan.text, /loaded in memory right now/);
	const changedId = planIdOf(plan.text)!;
	state.models = [ollamaModel('llama3.2:latest', 'd'.repeat(64))];
	const changed = await call('lm_delete_apply', { planId: changedId });
	assert.equal(changed.isError, true);
	assert.match(changed.text, /has changed since the plan/);
	assert.equal(ollama.calls.some(c => c.path === '/api/delete'), false);
	const id = planIdOf((await call('lm_delete_plan', { model: 'llama3.2:latest' })).text)!;
	const done = await call('lm_delete_apply', { planId: id });
	assert.equal(done.isError, false, done.text);
	assert.match(done.text, /Deleted llama3\.2:latest \(2\.0 GB, digest d{64}\)/);
	assert.deepEqual(ollama.calls.find(c => c.path === '/api/delete')!.body, { model: 'llama3.2:latest' });
	assert.equal(state.models.length, 0);
	assert.match((await call('lm_delete_apply', { planId: id })).text, /was not found/);
	assert.match((await call('lm_delete_plan', { model: 'llama3.2' })).text, /is not present in Ollama/);
	await close();
	await ollama.close();
});
const mode = (path: string) => statSync(path).mode & 0o777;
const pullPlan = (id: string): IPullPlan => ({ id, type: 'pull', createdAt: '', server: 'http://127.0.0.1:11434', model: 'm', existingDigest: null });
test('папки данных и планов 0700 (и у уже существующих), файл плана 0600', { skip: process.platform === 'win32' }, async () => {
	const env = { PLUGIN_DATA: mkdtempSync(join(tmpdir(), 'nb-lm-perm-')) };
	chmodSync(env.PLUGIN_DATA, 0o755);
	mkdirSync(plansRoot(env), { recursive: true });
	chmodSync(plansRoot(env), 0o755);
	const id = newPlanId();
	await savePlan(pullPlan(id), env);
	assert.equal(mode(env.PLUGIN_DATA), 0o700);
	assert.equal(mode(plansRoot(env)), 0o700);
	assert.equal(mode(join(plansRoot(env), `${id}.json`)), 0o600);
	assert.equal((await loadPlan<IPullPlan>(id, 'pull', env)).model, 'm');
});
test('планы старше суток не читаются и удаляются при сохранении нового', async () => {
	const env = { PLUGIN_DATA: mkdtempSync(join(tmpdir(), 'nb-lm-ttl-')) };
	const old = newPlanId();
	await savePlan(pullPlan(old), env);
	const past = (Date.now() - PLAN_TTL_MS - 60_000) / 1000;
	utimesSync(join(plansRoot(env), `${old}.json`), past, past);
	await assert.rejects(loadPlan(old, 'pull', env), /was not found/);
	const fresh = newPlanId();
	await savePlan(pullPlan(fresh), env);
	assert.equal(existsSync(join(plansRoot(env), `${old}.json`)), false);
	assert.deepEqual(readdirSync(plansRoot(env)), [`${fresh}.json`]);
});
