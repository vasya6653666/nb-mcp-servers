// Изменения в Temporal только парой «план → применение»: запуск Workflow, Signal, cancel / terminate. План сохраняет
// цель (отпечаток адреса и namespace) и для существующего выполнения — его Run ID; применение проверяет, что цель та же,
// а выполнение всё ещё в том же run и в статусе Running, исполняет ровно сохранённое и удаляет план.
import { IHandlerContext } from './context.js';
import { dropPlan, IPlanBase, loadPlan, newPlanId, savePlan } from './plans.js';
import { clip, redactText } from './redact.js';
import { APPLY_TIMEOUT } from './runner.js';
import { failure, nsArgs, parseJsonOutput, temporal, temporalTarget, verifyTemporalTarget } from './temporal.js';
import { describeExecution } from './temporalRead.js';

interface ITemporalPlan extends IPlanBase {
	readonly namespace?: string;
}

export interface IStartPlan extends ITemporalPlan {
	readonly type: 'temporal-start';
	readonly workflowType: string;
	readonly taskQueue: string;
	readonly workflowId?: string;
	readonly inputs: readonly string[];
	readonly executionTimeout?: string;
	readonly runTimeout?: string;
}

interface IRunPlan extends ITemporalPlan {
	readonly workflowId: string;
	readonly runId: string;
}

export interface ISignalPlan extends IRunPlan {
	readonly type: 'temporal-signal';
	readonly signal: string;
	readonly inputs: readonly string[];
}

export interface IStopPlan extends IRunPlan {
	readonly type: 'temporal-stop';
	readonly mode: 'cancel' | 'terminate';
	readonly reason?: string;
}

/** Вход: одна JSON-строка `input` или несколько аргументов `inputs`; передаются как есть, по флагу `--input` на каждый. */
function inputsOf(args: { input?: string; inputs?: readonly string[] }): string[] {
	if (args.input !== undefined && args.inputs?.length) {
		throw new Error('Pass either "input" (one argument) or "inputs" (several arguments), not both.');
	}
	return args.input !== undefined ? [args.input.trim()] : (args.inputs ?? []).map(value => value.trim());
}

const inputArgs = (inputs: readonly string[]) => inputs.map(value => `--input=${value}`);

function showInputs(inputs: readonly string[]): string {
	if (!inputs.length) {
		return 'Input: none.';
	}
	// Показ — для проверки пользователем: значения, похожие на пароли и токены, скрыты; отправлено будет как есть.
	return `Input (${inputs.length} argument(s); values that look like passwords or tokens are masked here, the plan sends them unchanged):\n${inputs.map((value, i) => `  [${i}] ${clip(redactText(value), 4000)}`).join('\n')}`;
}

export interface IStartArgs {
	readonly workflowType: string;
	readonly taskQueue: string;
	readonly workflowId?: string;
	readonly input?: string;
	readonly inputs?: readonly string[];
	readonly executionTimeout?: string;
	readonly runTimeout?: string;
	readonly namespace?: string;
}

export async function startPlan(ctx: IHandlerContext, args: IStartArgs): Promise<string> {
	const inputs = inputsOf(args);
	const target = await temporalTarget(ctx, args.namespace);
	const warnings: string[] = [];
	if (args.workflowId) {
		// «Не найдено» — нормальный случай для нового ID; любая другая ошибка (нет связи, нет прав) показывается.
		const existing = await describeExecution(ctx, args.workflowId, undefined, args.namespace).catch((error: Error) => {
			if (/not found/i.test(error.message)) {
				return undefined;
			}
			throw error;
		});
		if (existing?.status === 'Running') {
			warnings.push(`WARNING: an execution with this Workflow ID is Running (run ${existing.runId}, type ${existing.type}); the start will be refused while it runs.`);
		} else if (existing) {
			warnings.push(`Note: a closed execution with this Workflow ID exists (status ${existing.status}); the Namespace's ID reuse policy decides whether a new run is allowed.`);
		}
	}
	const id = newPlanId();
	const plan: IStartPlan = {
		id, type: 'temporal-start', createdAt: new Date().toISOString(), fingerprint: target.fingerprint, target: target.text,
		...args.namespace ? { namespace: args.namespace } : {}, workflowType: args.workflowType, taskQueue: args.taskQueue,
		...args.workflowId ? { workflowId: args.workflowId } : {}, inputs,
		...args.executionTimeout ? { executionTimeout: args.executionTimeout } : {}, ...args.runTimeout ? { runTimeout: args.runTimeout } : {},
	};
	await savePlan(plan, ctx.env);
	return [
		`Will start a new Workflow Execution on ${target.text}:`,
		`  type ${args.workflowType}, task queue ${args.taskQueue}, Workflow ID ${args.workflowId ?? '(generated by the server)'}`,
		...args.executionTimeout || args.runTimeout ? [`  execution timeout ${args.executionTimeout ?? '-'}, run timeout ${args.runTimeout ?? '-'}`] : [],
		showInputs(inputs),
		'Starting a Workflow runs its business logic in your Workers (activities may call external systems, send messages or move money).',
		...warnings,
		'',
		`Plan id: ${id}`,
		'To start exactly this Workflow after the user approves, call temporal_start_apply with this id.',
	].join('\n');
}

export async function startApply(ctx: IHandlerContext, args: { planId: string }): Promise<string> {
	const plan = await loadPlan<IStartPlan>(args.planId, 'temporal-start', ctx.env);
	try {
		await verifyTemporalTarget(ctx, plan);
		const flags = [`--type=${plan.workflowType}`, `--task-queue=${plan.taskQueue}`,
			...plan.workflowId ? [`--workflow-id=${plan.workflowId}`, '--fail-existing'] : [], ...inputArgs(plan.inputs),
			...plan.executionTimeout ? [`--execution-timeout=${plan.executionTimeout}`] : [], ...plan.runTimeout ? [`--run-timeout=${plan.runTimeout}`] : [],
			...nsArgs(plan.namespace), '--output=json'];
		const result = await temporal(ctx, ['workflow', 'start', ...flags], APPLY_TIMEOUT);
		if (result.code !== 0) {
			throw failure('temporal workflow start', result);
		}
		const started = parseJsonOutput<{ workflowId?: string; runId?: string } | null>(result.stdout, 'temporal workflow start');
		return `Started Workflow ${started?.workflowId ?? '?'} (run ${started?.runId ?? '?'}), type ${plan.workflowType}, on ${plan.target}.\nUse temporal_workflow_describe to follow it.`;
	} finally {
		// План одноразовый: после запуска, отказа CLI или несовпадения цели он больше не нужен.
		await dropPlan(plan.id, ctx.env);
	}
}

/** Текущее выполнение для плана: должно быть Running; Run ID закрепляется. */
async function runningExecution(ctx: IHandlerContext, workflowId: string, runId: string | undefined, namespace: string | undefined, action: string) {
	const exec = await describeExecution(ctx, workflowId, runId, namespace);
	if (exec.status !== 'Running') {
		throw new Error(`Workflow ${workflowId} (run ${exec.runId}) is ${exec.status}, not Running; nothing to ${action}.`);
	}
	return exec;
}

/** Перед применением: цель та же, выполнение в том же run и всё ещё Running. */
async function verifyRun(ctx: IHandlerContext, plan: IRunPlan, again: string): Promise<void> {
	await verifyTemporalTarget(ctx, plan);
	const exec = await describeExecution(ctx, plan.workflowId, plan.runId, plan.namespace).catch(() => undefined);
	if (!exec || exec.runId !== plan.runId || exec.status !== 'Running') {
		throw new Error(`Workflow ${plan.workflowId} run ${plan.runId} is ${exec ? exec.status : 'no longer found'}, not Running as when the plan was made. The plan was discarded; run ${again} again.`);
	}
}

export async function signalPlan(ctx: IHandlerContext, args: { workflowId: string; runId?: string; signal: string; input?: string; inputs?: readonly string[]; namespace?: string }): Promise<string> {
	const inputs = inputsOf(args);
	const target = await temporalTarget(ctx, args.namespace);
	const exec = await runningExecution(ctx, args.workflowId, args.runId, args.namespace, 'signal');
	const id = newPlanId();
	const plan: ISignalPlan = {
		id, type: 'temporal-signal', createdAt: new Date().toISOString(), fingerprint: target.fingerprint, target: target.text,
		...args.namespace ? { namespace: args.namespace } : {}, workflowId: args.workflowId, runId: exec.runId, signal: args.signal, inputs,
	};
	await savePlan(plan, ctx.env);
	return [
		`Will send Signal "${args.signal}" to Workflow ${args.workflowId} (run ${exec.runId}, type ${exec.type}, status Running) on ${target.text}.`,
		showInputs(inputs),
		'The Workflow code decides what the Signal does; it is recorded in the Event History and cannot be taken back.',
		'',
		`Plan id: ${id}`,
		'To send exactly this Signal after the user approves, call temporal_signal_apply with this id.',
	].join('\n');
}

export async function signalApply(ctx: IHandlerContext, args: { planId: string }): Promise<string> {
	const plan = await loadPlan<ISignalPlan>(args.planId, 'temporal-signal', ctx.env);
	try {
		await verifyRun(ctx, plan, 'temporal_signal_plan');
		const result = await temporal(ctx, ['workflow', 'signal', `--workflow-id=${plan.workflowId}`, `--run-id=${plan.runId}`, `--name=${plan.signal}`,
			...inputArgs(plan.inputs), ...nsArgs(plan.namespace)], APPLY_TIMEOUT);
		if (result.code !== 0) {
			throw failure('temporal workflow signal', result);
		}
		return `Sent Signal "${plan.signal}" to Workflow ${plan.workflowId} (run ${plan.runId}) on ${plan.target}.\n${redactText(result.stdout.trim())}`;
	} finally {
		await dropPlan(plan.id, ctx.env);
	}
}

export async function stopPlan(ctx: IHandlerContext, args: { workflowId: string; runId?: string; mode: 'cancel' | 'terminate'; reason?: string; namespace?: string }): Promise<string> {
	if (args.mode === 'cancel' && args.reason) {
		throw new Error('"reason" is recorded only for terminate; the CLI does not send a reason with a single cancel. Remove it or use mode "terminate".');
	}
	const target = await temporalTarget(ctx, args.namespace);
	const exec = await runningExecution(ctx, args.workflowId, args.runId, args.namespace, args.mode);
	const pending = Array.isArray(exec.raw['pendingActivities']) ? exec.raw['pendingActivities'].length : 0;
	const id = newPlanId();
	const plan: IStopPlan = {
		id, type: 'temporal-stop', createdAt: new Date().toISOString(), fingerprint: target.fingerprint, target: target.text,
		...args.namespace ? { namespace: args.namespace } : {}, workflowId: args.workflowId, runId: exec.runId, mode: args.mode,
		...args.reason ? { reason: args.reason } : {},
	};
	await savePlan(plan, ctx.env);
	const effect = args.mode === 'cancel'
		? 'Cancel requests cancellation: the Workflow code receives it and may run cleanup (compensations) before it closes as Canceled.'
		: `Terminate closes the run immediately as Terminated: the Workflow code gets no chance to clean up, pending activities are abandoned${args.reason ? `; reason "${args.reason}"` : '; the reason defaults to the CLI user name'}.`;
	return [
		`Will ${args.mode} Workflow ${args.workflowId} (run ${exec.runId}) on ${target.text}.`,
		`Current state: type ${exec.type}, status ${exec.status}, task queue ${exec.taskQueue || '-'}, ${pending} pending activit${pending === 1 ? 'y' : 'ies'}.`,
		effect,
		'',
		`Plan id: ${id}`,
		`To ${args.mode} exactly this run after the user approves, call temporal_stop_apply with this id.`,
	].join('\n');
}

export async function stopApply(ctx: IHandlerContext, args: { planId: string }): Promise<string> {
	const plan = await loadPlan<IStopPlan>(args.planId, 'temporal-stop', ctx.env);
	try {
		await verifyRun(ctx, plan, 'temporal_stop_plan');
		const run = [`--workflow-id=${plan.workflowId}`, `--run-id=${plan.runId}`, ...nsArgs(plan.namespace)];
		const result = plan.mode === 'cancel'
			? await temporal(ctx, ['workflow', 'cancel', ...run], APPLY_TIMEOUT)
			: await temporal(ctx, ['workflow', 'terminate', ...run, ...plan.reason ? [`--reason=${plan.reason}`] : []], APPLY_TIMEOUT);
		if (result.code !== 0) {
			throw failure(`temporal workflow ${plan.mode}`, result);
		}
		return `${plan.mode === 'cancel' ? 'Cancellation requested for' : 'Terminated'} Workflow ${plan.workflowId} (run ${plan.runId}) on ${plan.target}.\n${redactText(result.stdout.trim())}`;
	} finally {
		await dropPlan(plan.id, ctx.env);
	}
}
