// Регистрация инструментов Temporal: описания и пометки для клиента. Чтение — `temporalRead.ts`, изменения парой
// «план → применение» — `temporalChanges.ts`. Вызывает `server.ts`.
import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { z } from 'zod';
import { IHandlerContext } from './context.js';
import { APPROVAL, duration, jsonText, plainText, planId, reply, runId, temporalNamespace as namespace, workflowId } from './reply.js';
import { signalApply, signalPlan, startApply, startPlan, stopApply, stopPlan } from './temporalChanges.js';
import { taskQueueDescribe, workflowDescribe, workflowHistory, workflowList } from './temporalRead.js';

const READ = { readOnlyHint: true, openWorldHint: true } as const;
const PLAN = { readOnlyHint: false, destructiveHint: false, idempotentHint: false, openWorldHint: true } as const;
const APPLY = { readOnlyHint: false, destructiveHint: true, idempotentHint: false, openWorldHint: true } as const;
const NO_PAYLOADS = 'Payload contents (inputs, results, memo, heartbeat details) are never shown, only their size.';

export function registerTemporalTools(server: McpServer, ctx: IHandlerContext): void {
	const input = jsonText.optional().describe('One Workflow argument as a JSON value, for example \'{"orderId": "A-17"}\'. Sent unchanged.');
	const inputs = z.array(jsonText).max(20).optional().describe('Several Workflow arguments, each a JSON value, in order. Use instead of "input".');
	server.registerTool('temporal_workflow_list', {
		title: 'List Temporal Workflow Executions',
		description: 'List Workflow Executions of a Namespace with temporal workflow list: status, Workflow ID, Run ID, type, task queue, start and close age. "query" is a List Filter, for example "ExecutionStatus = \'Running\' AND WorkflowType = \'OrderWorkflow\'". Read-only.',
		inputSchema: {
			query: plainText('Query', 4000).optional().describe('List Filter (SQL-like Visibility query).'),
			limit: z.number().int().min(1).max(1000).optional().describe('Maximum number of executions. Default 50.'),
			namespace: namespace.optional(),
		},
		annotations: READ,
	}, args => reply(() => workflowList(ctx, args)));
	server.registerTool('temporal_workflow_describe', {
		title: 'Describe a Temporal Workflow Execution',
		description: `Show one Workflow Execution: status, type, task queue, start and close time, history size, pending activities with attempts and last failure messages, pending child workflows, and the failure of a failed run. ${NO_PAYLOADS} Read-only.`,
		inputSchema: { workflowId, runId: runId.optional(), namespace: namespace.optional() },
		annotations: READ,
	}, args => reply(() => workflowDescribe(ctx, args)));
	server.registerTool('temporal_workflow_history', {
		title: 'Show a Temporal Event History',
		description: `Show the Event History of a Workflow Execution as a short timeline: event id, time, event type, and details such as activity type, signal name, timer, attempt and failure message. ${NO_PAYLOADS} Read-only.`,
		inputSchema: {
			workflowId, runId: runId.optional(),
			limit: z.number().int().min(1).max(5000).optional().describe('Show only the last N events. Default 200.'),
			namespace: namespace.optional(),
		},
		annotations: READ,
	}, args => reply(() => workflowHistory(ctx, args)));
	server.registerTool('temporal_task_queue_describe', {
		title: 'Describe a Temporal task queue',
		description: 'Show the Workers polling a task queue (identity, build id, last poll) and backlog statistics. An empty poller list means no Worker is processing the queue. Read-only.',
		inputSchema: {
			taskQueue: plainText('Task queue').describe('Task queue name.'),
			taskQueueType: z.enum(['workflow', 'activity', 'nexus']).optional().describe('Only this task queue type. Default: all types.'),
			namespace: namespace.optional(),
		},
		annotations: READ,
	}, args => reply(() => taskQueueDescribe(ctx, args)));
	server.registerTool('temporal_start_plan', {
		title: 'Plan a Workflow start',
		description: 'Show exactly which Workflow would be started (type, Workflow ID, task queue, input, timeouts, target address and Namespace), warn when an execution with the same Workflow ID is running, and save a plan for temporal_start_apply. Starts nothing.',
		inputSchema: {
			workflowType: plainText('Workflow type').describe('Workflow Type name.'),
			taskQueue: plainText('Task queue').describe('Task queue the Workers poll.'),
			workflowId: workflowId.optional().describe('Workflow ID. Default: generated by the server. Set it to make the start idempotent.'),
			input, inputs,
			executionTimeout: duration.optional().describe('Fail the Workflow Execution if it lasts longer, for example "1h".'),
			runTimeout: duration.optional().describe('Fail a single run if it lasts longer.'),
			namespace: namespace.optional(),
		},
		annotations: PLAN,
	}, args => reply(() => startPlan(ctx, args)));
	server.registerTool('temporal_start_apply', {
		title: 'Start a planned Workflow',
		description: `Start exactly the Workflow saved by temporal_start_plan, on the same address and Namespace; with a Workflow ID it refuses to attach to an already running execution. Runs real business logic in the Workers. ${APPROVAL}`,
		inputSchema: { planId },
		annotations: APPLY,
	}, args => reply(() => startApply(ctx, args)));
	server.registerTool('temporal_signal_plan', {
		title: 'Plan a Signal',
		description: 'Check that the Workflow Execution is Running, pin its Run ID, show the Signal name and input, and save a plan for temporal_signal_apply. Sends nothing.',
		inputSchema: {
			workflowId, runId: runId.optional(),
			signal: plainText('Signal name').describe('Signal name.'),
			input, inputs, namespace: namespace.optional(),
		},
		annotations: PLAN,
	}, args => reply(() => signalPlan(ctx, args)));
	server.registerTool('temporal_signal_apply', {
		title: 'Send a planned Signal',
		description: `Send exactly the Signal saved by temporal_signal_plan to the pinned run. Refuses if the run is no longer Running or the target changed. ${APPROVAL}`,
		inputSchema: { planId },
		annotations: APPLY,
	}, args => reply(() => signalApply(ctx, args)));
	server.registerTool('temporal_stop_plan', {
		title: 'Plan a cancel or terminate',
		description: 'Check that the Workflow Execution is Running, show its current state, explain the effect of cancel (Workflow cleanup runs) or terminate (immediate, no cleanup), pin its Run ID and save a plan for temporal_stop_apply. Changes nothing.',
		inputSchema: {
			workflowId, runId: runId.optional(),
			mode: z.enum(['cancel', 'terminate']).describe('"cancel" asks the Workflow to cancel itself; "terminate" ends it at once.'),
			reason: plainText('Reason').optional().describe('Reason recorded with terminate.'),
			namespace: namespace.optional(),
		},
		annotations: PLAN,
	}, args => reply(() => stopPlan(ctx, args)));
	server.registerTool('temporal_stop_apply', {
		title: 'Cancel or terminate a planned run',
		description: `Cancel or terminate exactly the run pinned by temporal_stop_plan. Refuses if the run is no longer Running or the target changed. Termination cannot be undone. ${APPROVAL}`,
		inputSchema: { planId },
		annotations: APPLY,
	}, args => reply(() => stopApply(ctx, args)));
}
